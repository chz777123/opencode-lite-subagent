#!/usr/bin/env node
// Build src/assets.js from config/. config/ is the only source of truth.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));

function splitFrontmatter(text) {
  const lines = text.split(/\r?\n/);
  if (lines[0]?.trim() !== "---") return { data: {}, body: text };
  const end = lines.findIndex((line, index) => index > 0 && line.trim() === "---");
  if (end === -1) return { data: {}, body: text };

  const data = {};
  for (const line of lines.slice(1, end)) {
    if (!line.trim() || line.trimStart().startsWith("#")) continue;
    const match = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (!match) continue;
    let value = match[2].trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    data[match[1]] = value;
  }

  return { data, body: lines.slice(end + 1).join("\n").replace(/^\n/, "") };
}

function read(relative) {
  return readFileSync(join(root, relative), "utf8");
}

const agentFiles = readdirSync(join(root, "config/agents"))
  .filter((file) => file.endsWith(".md"))
  .sort();

const agents = agentFiles.map((file) => ({
  id: file.slice(0, -".md".length),
  content: read(`config/agents/${file}`),
}));

const commandFiles = readdirSync(join(root, "config/commands"))
  .filter((file) => file.endsWith(".md"))
  .sort();

const commands = commandFiles.map((file) => {
  const { data, body } = splitFrontmatter(read(`config/commands/${file}`));
  return {
    name: file.slice(0, -".md".length),
    description: data.description ?? "",
    agent: data.agent ?? "",
    body,
  };
});

const skillDirs = readdirSync(join(root, "config/skills"), { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const skills = skillDirs.map((id) => {
  const { data, body } = splitFrontmatter(read(`config/skills/${id}/SKILL.md`));
  return {
    id,
    name: data.name ?? id,
    description: data.description ?? "",
    content: body,
  };
});

const output = `// Generated by scripts/build-assets.mjs. Do not edit by hand.
// Source of truth: config/

export const agents = ${JSON.stringify(agents, null, 2)};

export const commands = ${JSON.stringify(commands, null, 2)};

export const skills = ${JSON.stringify(skills, null, 2)};
`;

writeFileSync(join(root, "src/assets.js"), output);
console.log(
  `built src/assets.js: ${agents.length} agents, ${commands.length} commands, ${skills.length} skills`,
);
